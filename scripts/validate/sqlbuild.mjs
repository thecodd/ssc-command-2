/** Catalog-driven privilege checks generated from function_matrix.js + the migrations (the same inputs 014 is generated from). */
export function securityCatalogSql() {
  const { collect, qual } = require(path.join(root, "database/security/build_privileges.js"));
  const matrix = require(path.join(root, "database/security/function_matrix.js"));
  const AUTH = new Set(["rpc", "admin", "rls", "pure"]);
  const rows = collect().map((f) => {
    const cls = matrix[f.name]?.cls; if (!cls) throw new Error(`function ${f.name} is not classified in function_matrix.js`);
    return { sig: `public.${f.name}(${f.types.map(qual).join(",")})`, name: f.name, cls, auth: AUTH.has(cls), svc: cls === "service" };
  });
  const q = (s) => "'" + s.replace(/'/g, "''") + "'";
  return `-- ---- SEC catalog (generated by scripts/validate/sqlbuild.mjs from function_matrix.js; ${rows.length} functions) ----
create temp table t_fn_expect (sig text, name text, cls text, auth_exec boolean, svc_only boolean);
insert into t_fn_expect values
${rows.map((r) => `  (${q(r.sig)}, ${q(r.name)}, ${q(r.cls)}, ${r.auth}, ${r.svc})`).join(",\n")};
`;
}
