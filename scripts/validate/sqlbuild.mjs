const NS_DNS = Buffer.from("6ba7b8109dad11d180b400c04fd430c8", "hex");
export function uuid5(name) {
  const h = crypto.createHash("sha1").update(Buffer.concat([NS_DNS, Buffer.from(name, "utf8")])).digest();
  const b = Buffer.from(h.subarray(0, 16)); b[6] = (b[6] & 0x0f) | 0x50; b[8] = (b[8] & 0x3f) | 0x80;
  const x = b.toString("hex"); return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}
function substitute(text) {
  const tokens = [...new Set([...text.matchAll(/@([A-Z0-9]+)@/g)].map((m) => m[1]))].sort();
  for (const t of tokens) text = text.split(`@${t}@`).join(uuid5("cgl-command-test-" + t));
  const left = text.match(/@[A-Z0-9]+@/g); if (left) throw new Error("unsubstituted tokens: " + [...new Set(left)].join(","));
  return { text, tokens: tokens.length };
}
