export function checkSuite(key) { const s = SUITES[key]; if (!fs.existsSync(s.out)) return { key, ok: false, why: "built file missing" }; const want = s.build().text; return { key, ok: read(s.out) === want, why: read(s.out) === want ? "" : "committed file differs from a fresh build" }; }
